// 개인정보 가림 [팀 설계안] — AI에 보내기 전에 정규식으로 *** 처리
const RULES = [
  [/\d{6}\s*-\s*[1-4]\d{6}/g, '***'],                       // 주민등록번호
  [/01[016789][\s-]?\d{3,4}[\s-]?\d{4}/g, '***'],            // 휴대전화
  [/0\d{1,2}[\s-]\d{3,4}[\s-]\d{4}/g, '***'],                // 일반 전화
  [/[\w.+-]+@[\w-]+\.[\w.]+/g, '***'],                       // 이메일
  [/[가-힣]+(로|길)\s?\d+(-\d+)?(번길)?\s?\d*(-\d+)?/g, '***'], // 도로명 주소
  [/[가-힣]+동\s?\d+(-\d+)?번지/g, '***'],                    // 지번 주소
  [/(이름|성명|작성자)\s*[:：]?\s*[가-힣]{2,4}/g, '$1: ***'],  // 이름: 홍길동
  [/[가-힣]{2,4}\s?(씨|님)(?=[이가은는을를의께,\s])/g, '***$1'], // 홍길동 씨
];

function maskPII(text) {
  let out = String(text || '');
  let count = 0;
  for (const [re, rep] of RULES) out = out.replace(re, (...m) => { count++; return rep.replace('$1', m[1] || ''); });
  return { text: out, count };
}

module.exports = { maskPII };
