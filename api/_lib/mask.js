// 개인정보 가림 [팀 설계안] — AI에 보내기 전에 정규식으로 *** 처리
const RULES = [
  [/\d{6}\s*-\s*[1-4]\d{6}/g, '***'],                       // 주민등록번호
  [/01[016789][\s-]?\d{3,4}[\s-]?\d{4}/g, '***'],            // 휴대전화
  [/0\d{1,2}[\s-]\d{3,4}[\s-]\d{4}/g, '***'],                // 일반 전화
  [/[\w.+-]+@[\w-]+\.[\w.]+/g, '***'],                       // 이메일
  // 도로명 주소: 「보문로 34」「보문로34길 5」는 가리고, 「보문로 3번 출구」「골목길 2주째」처럼 숫자 뒤에 단위가 붙으면 두지 않음
  [/[가-힣]+(로|길)\s?\d+(-\d+)?(번?길\s?\d+(-\d+)?)?(?![\d-])(?!\s?(번|주|일|시|분|개|월|년|명|대|층|차|호선|번째|미터|m|km))/g, '***'],
  [/[가-힣]+동\s?\d+(-\d+)?번지/g, '***'],                    // 지번 주소
  [/(이름|성명|작성자)\s*[:：]?\s*[가-힣]{2,4}/g, '$1: ***'],  // 이름: 홍길동
  [/[가-힣]{2,4}\s?(씨|님)(?=[이가은는을를의께,\s])/g, '***$1', 'name'], // 홍길동 씨 (직함은 아래 TITLE 로 제외)
];

// 「담당자님」「구청장님」처럼 직함·호칭 뒤에 붙은 님/씨는 이름이 아니므로 가리지 않는다
const TITLE = /(담당자?|구청장|청장|동장|시장|주무관|공무원|직원|과장|팀장|국장|실장|계장|부장|소장|원장|사장|이사장|대표|의원|위원|선생|교수|기사|관리자|관리인|경비원|경찰관|민원인|주민|이웃|어르신|고객|손|형|누|언니|오빠|아버|어머|할아버|할머|사모|회장|반장|통장|센터장)$/;

function maskPII(text) {
  let out = String(text || '');
  let count = 0;
  for (const [re, rep, kind] of RULES) out = out.replace(re, (...m) => {
    if (kind === 'name' && TITLE.test(m[0].replace(/\s?(씨|님)$/, ''))) return m[0];
    count++; return rep.replace('$1', m[1] || '');
  });
  return { text: out, count };
}

module.exports = { maskPII };
